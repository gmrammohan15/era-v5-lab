"""Write one Kaggle kernel for a stage plan and push it (private, T4, internet on). Runs on the laptop.

    python push.py --kernel k0 --sha <commit on the public fork> --dir <scratch folder> [--dry-run]

The kernel clones the public fork at --sha and runs stage.py there; no file from the laptop is uploaded except the
generated kernel script, and no credential enters it (the kaggle CLI reads its own token file). Each plan is a list
of groups run one after another; the stages of a group run at the same time, one per GPU.
Earlier kernels named in `sources` are mounted read-only by Kaggle; their W folders are linked into this run's W.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

USER = "gmrammohan"
FORK = "https://github.com/gmrammohan15/era-v5-lab.git"
PIP = ["transformers==5.19.0", "math-verify==0.9.0", "pyyaml", "pytest"]
STAGE = "teams/10-post-training/capstone/kaggle_e2e/stage.py"


def plans(grpo_steps: int, grpo_seconds: int, sft_model: str) -> dict:
    sft = "/kaggle/working/w/sft_{}/model"
    return {
        "k0": {"title": "g10-e2e-k0-smoke", "sources": [],
               "groups": [[["prep"]], [["smoke"]]], "keep": ["prep", "smoke", "smoke_sft_adamw", "smoke_sft_hybrid",
                                                            "grpo_adamw"]},
        "k1": {"title": "g10-e2e-k1-sft", "sources": [],
               "groups": [[["prep"]],
                          [["sft", "--arm", "adamw", "--pack", "--gpu", "0"],
                           ["sft", "--arm", "hybrid_muon", "--pack", "--gpu", "1"]],
                          [["eval", "--model", sft.format("adamw"), "--name", "sft_adamw", "--gpu", "0"],
                           ["eval", "--model", sft.format("hybrid_muon"), "--name", "sft_hybrid_muon", "--gpu", "1"]],
                          [["eval", "--model", "/kaggle/working/w/src/model", "--name", "base", "--gpu", "0"]]],
               "keep": ["prep", "sft_adamw", "sft_hybrid_muon", "eval_sft_adamw", "eval_sft_hybrid_muon", "eval_base"]},
        "k3": {"title": "g10-e2e-k3-grpo", "sources": ["g10-e2e-k1-sft"],
               "groups": [[["grpo", "--sft-model", sft_model, "--optim", "adamw", "--steps", str(grpo_steps),
                            "--max-seconds", str(grpo_seconds), "--gpu", "0"],
                           ["grpo", "--sft-model", sft_model, "--optim", "hybrid_muon", "--steps", str(grpo_steps),
                            "--max-seconds", str(grpo_seconds), "--gpu", "1"]]],
               "keep": ["grpo_adamw", "grpo_hybrid_muon"]},
        "k4": {"title": "g10-e2e-k4-eval", "sources": ["g10-e2e-k1-sft", "g10-e2e-k3-grpo"],
               "groups": [[["eval", "--model", "/kaggle/working/w/grpo_adamw/final_model", "--name", "grpo_adamw",
                            "--gpu", "0"],
                           ["eval", "--model", "/kaggle/working/w/grpo_hybrid_muon/final_model",
                            "--name", "grpo_hybrid_muon", "--gpu", "1"]]],
               "keep": ["eval_grpo_adamw", "eval_grpo_hybrid_muon"]},
    }


KERNEL = '''# Generated by teams/10-post-training/capstone/kaggle_e2e/push.py ({kernel}); public sources only.
import json, os, pathlib, shutil, subprocess, sys, time
SHA = {sha!r}
GROUPS = {groups!r}
KEEP = {keep!r}
W = pathlib.Path("/kaggle/working/w")
R = pathlib.Path("/kaggle/repo")
def sh(cmd):
    print("$", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)
t0 = time.time()
sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
sh("pip install -q " + {pip!r})
sh(f"git init -q {{R}} && cd {{R}} && git remote add origin {fork} && git fetch -q --depth 1 origin {{SHA}} "
   f"&& git checkout -q FETCH_HEAD && git log -1 --format=%H")
W.mkdir(parents=True, exist_ok=True)
for m in pathlib.Path("/kaggle/input").rglob("manifest.json"):  # earlier kernels' W folders
    d = m.parent
    if d.parent.name == "w" and not (W / d.name).exists():
        (W / d.name).symlink_to(d)
        print("linked", d, flush=True)
status = {{"sha": SHA, "groups": []}}
for group in GROUPS:
    if not (W / "src" / "model" / "model.safetensors").exists() and group[0][0] != "prep":
        sh(f"{{sys.executable}} {{R / {stage!r}}} fetch --work {{W}}")
    procs = [subprocess.Popen([sys.executable, str(R / {stage!r}), *argv, "--work", str(W)]) for argv in group]
    codes = [p.wait() for p in procs]
    status["groups"].append({{"argv": group, "exit": codes, "elapsed_s": round(time.time() - t0, 1)}})
    (pathlib.Path("/kaggle/working") / "status.json").write_text(json.dumps(status, indent=1))
    if any(codes):
        break
for p in list(W.iterdir()):
    if p.is_symlink() or p.name not in KEEP:
        p.unlink() if p.is_symlink() or p.is_file() else shutil.rmtree(p)
for big in list(W.rglob("train_state.pt")) + list(W.rglob("state")):
    shutil.rmtree(big) if big.is_dir() else big.unlink()
status["seconds"] = round(time.time() - t0, 1)
(pathlib.Path("/kaggle/working") / "status.json").write_text(json.dumps(status, indent=1))
print(json.dumps(status), flush=True)
if any(any(g["exit"]) for g in status["groups"]):
    sys.exit(1)
'''


def kernel_files(kernel: str, sha: str, plan: dict) -> tuple[str, dict]:
    if not re.fullmatch(r"[0-9a-f]{40}", sha):
        raise SystemExit("--sha must be a full 40-hex commit id")
    script = KERNEL.format(kernel=kernel, sha=sha, groups=plan["groups"], keep=plan["keep"], pip=" ".join(PIP),
                           fork=FORK, stage=STAGE)
    meta = {"id": f"{USER}/{plan['title']}", "title": plan["title"], "code_file": "kernel.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
            "machine_shape": "NvidiaTeslaT4", "dataset_sources": [], "competition_sources": [],
            "kernel_sources": [f"{USER}/{s}" for s in plan["sources"]]}
    return script, meta


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--kernel", required=True, choices=("k0", "k1", "k3", "k4"))
    ap.add_argument("--sha", required=True)
    ap.add_argument("--dir", type=Path, required=True, help="scratch folder for the generated kernel (not the repo)")
    ap.add_argument("--grpo-steps", type=int, default=100)
    ap.add_argument("--grpo-seconds", type=int, default=5 * 3600)
    ap.add_argument("--sft-model", default="/kaggle/working/w/sft_adamw/model")
    ap.add_argument("--kaggle", default="kaggle")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    plan = plans(args.grpo_steps, args.grpo_seconds, args.sft_model)[args.kernel]
    script, meta = kernel_files(args.kernel, args.sha, plan)
    out = args.dir / args.kernel
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(script)
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    compile(script, str(out / "kernel.py"), "exec")
    print(json.dumps({"kernel": meta["id"], "dir": str(out), "groups": len(plan["groups"])}))
    if not args.dry_run:
        subprocess.run([args.kaggle, "kernels", "push", "-p", str(out)], check=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
